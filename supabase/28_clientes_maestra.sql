-- =====================================================================
-- 28: Base Maestra de Clientes
--
-- clientes                 una fila por cliente, con ID permanente.
--   id_cliente  text  'CLI-0001'… Lo genera el panel (siguiente correlativo)
--                     y NUNCA cambia, aunque se edite el nombre.
--   nombre      text  razón social normalizada (formato de la base: MAYÚSCULAS).
--   nombre_clave text MAYÚSCULAS sin tildes, espacios ni signos. Es único:
--                     evita duplicados exactos ("AGRICOLA CHAPI SA" = "Agrícola Chapi S.A.").
--
-- oportunidades.cliente_id  vínculo con la Base Maestra. oportunidades.cliente
--   sigue guardando el nombre (lo leen filtros, dashboards y reportes); el panel
--   lo mantiene igual al nombre maestro. Las oportunidades antiguas quedan con
--   cliente_id NULL y su nombre intacto hasta que se editen en la ficha.
--   Sin foreign key a propósito: el panel puede subir la oportunidad antes que
--   el cliente recién creado y una FK rechazaría el guardado completo.
--
-- Semilla: los 253 clientes de "Clientes_Unicos_253.xlsx" (CLI-0001…CLI-0253).
--
-- Compatibilidad: idempotente ("if not exists" / "on conflict do nothing"),
-- se puede correr varias veces. Mientras no se corra, el panel usa la misma
-- semilla y guarda los clientes nuevos solo en el navegador.
--
-- Ejecutar en Supabase: Dashboard -> SQL Editor -> New query -> pegar y Run.
-- =====================================================================

create table if not exists public.clientes (
  id_cliente     text primary key,
  nombre         text not null,
  nombre_clave   text not null,
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  creado_por     text
);

create unique index if not exists clientes_nombre_clave_uidx on public.clientes (nombre_clave);

comment on table public.clientes is
  'Base Maestra de Clientes. id_cliente es permanente; el nombre se puede editar sin perder los vínculos.';

alter table public.oportunidades add column if not exists cliente_id text;
create index if not exists oportunidades_cliente_id_idx on public.oportunidades (cliente_id);
comment on column public.oportunidades.cliente_id is
  'ID de la Base Maestra de Clientes (public.clientes.id_cliente). NULL = registro histórico sin vincular.';

-- ---------------------------------------------------------------------
-- Permisos: leen todos los perfiles con rol, escriben admin y editor.
-- Sin política de delete: un cliente no se borra (conserva los vínculos).
-- ---------------------------------------------------------------------
alter table public.clientes enable row level security;

drop policy if exists "clientes_select_con_perfil" on public.clientes;
create policy "clientes_select_con_perfil" on public.clientes
  for select to authenticated using (public.mi_rol() is not null);

drop policy if exists "clientes_insert_editor" on public.clientes;
create policy "clientes_insert_editor" on public.clientes
  for insert to authenticated with check (public.puede_editar());

drop policy if exists "clientes_update_editor" on public.clientes;
create policy "clientes_update_editor" on public.clientes
  for update to authenticated using (public.puede_editar()) with check (public.puede_editar());

